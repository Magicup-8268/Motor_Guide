export function categoriesForBrand(brandId: BrandCatalog['id']) {
  const profile = categoryProfiles[brandId]
  return categories.map((category) => ({ ...category, ...profile?.[category.id] }))
}

export function categoryForBrand(brandId: BrandCatalog['id'], categoryId: MotorCategory['id']) {
  return categoriesForBrand(brandId).find((category) => category.id === categoryId)!
}

